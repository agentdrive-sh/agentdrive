// Deploys a community-supported, self-hosted AgentDrive API to your own
// Cloudflare account with your existing `wrangler login`. Safe to re-run:
// resources are reused by name, secrets that already exist are never replaced,
// and the worker is redeployed from the current checkout.
//
//   pnpm selfhost [--name agentdrive] [--backup-secrets <new-file>] [--register] [--dry-run]
//
// A self-hosted instance is API-key only. --register issues a new owner key in the
// instance's one org: the recovery path for a lost key or a first registration that failed.
//
// --dry-run uses placeholder IDs and runs `wrangler deploy --dry-run` only: no
// account access, no resources, no deploy.

// Mirrors EMBEDDING_DIMS in src/services/embeddings.ts and the production index
// (768 dimensions, cosine, string metadata indexes on every property the search
// and context filters use); the selfhost test holds them together.
export const VECTORIZE = { dimensions: 768, metric: 'cosine', metadata: ['org_id', 'ws_id', 'agent_id', 'agent_platform'] };
export const SECRETS = ['TOKEN_SIGNING_SECRET', 'BUCKET_KEK_ROOT', 'BUCKET_KEK_VERSION'] as const;
export const PLACEHOLDER_URL = 'https://selfhost.invalid';

export const PLAN_NOTE = `Cloudflare plan: Workers Paid ($5/month) is required.
  - Durable Objects: FileCollab uses the key-value storage backend, which only Workers Paid can create.
  - CPU: Workers Free allows 10 ms per request; uploads, search and encryption need more.
  KV, R2, Vectorize and Workers AI bill against their own free allowances first. R2 must be
  enabled once in the dashboard. Rate limiting bindings have no documented plan requirement.`;

export interface Block {
  header: string;
  lines: string[];
}

// Comments and blank lines are dropped: the generated file carries no production notes.
export function blocks(toml: string): Block[] {
  const out: Block[] = [{ header: '', lines: [] }];
  for (const raw of toml.split('\n')) {
    const line = raw.trimEnd();
    if (!line.trim() || line.trim().startsWith('#')) continue;
    if (/^\[/.test(line)) out.push({ header: line.trim(), lines: [] });
    else out[out.length - 1]!.lines.push(line);
  }
  return out;
}

export function value(block: Block, key: string): string | undefined {
  for (const line of block.lines) {
    const m = new RegExp(`^${key}\\s*=\\s*"([^"]*)"`).exec(line.trim());
    if (m) return m[1];
  }
  return undefined;
}

function set(block: Block, key: string, next: string): string[] {
  if (value(block, key) === undefined) throw new Error(`${block.header} has no ${key}`);
  return block.lines.map((line) => (new RegExp(`^${key}\\s*=`).test(line.trim()) ? `${key} = ${JSON.stringify(next)}` : line));
}

export function resourceName(name: string, binding: string): string {
  return `${name}-${binding.toLowerCase().replace(/_/g, '-')}`;
}

export interface SelfhostOptions {
  name: string;
  url: string;
  kvIds: Record<string, string>;
  // A service binding to a worker that doesn't exist yet fails the deploy, so the very
  // first deploy goes out without it and the second adds it.
  selfBinding: boolean;
}

const KEEP = new Set(['[observability]', '[observability.logs]', '[durable_objects]', '[[migrations]]', '[ai]', '[[ratelimits]]']);
// send_email: a self-hosted instance has no email sign-in, so it never sends mail.
const DROP = new Set(['[[routes]]', '[assets]', '[[send_email]]']);
const TOP_KEEP = new Set(['main', 'compatibility_date', 'compatibility_flags']);
const TOP_DROP = new Set(['route', 'routes', 'account_id', 'workers_dev']);

// Allow-list, so a new production section fails loudly here instead of
// reaching a self-hosted deploy with a production ID or route in it.
export function selfhostConfig(prod: string, o: SelfhostOptions): string {
  const out = ['# Generated by `pnpm selfhost` from wrangler.toml. Do not edit; re-run it instead.'];
  for (const b of blocks(prod)) {
    let lines: string[];
    if (b.header === '') {
      lines = [`name = ${JSON.stringify(o.name)}`, 'workers_dev = true'];
      for (const line of b.lines) {
        const key = line.split('=')[0]!.trim();
        if (TOP_KEEP.has(key)) lines.push(line);
        else if (key !== 'name' && !TOP_DROP.has(key)) throw new Error(`selfhost.ts does not know top-level key "${key}"`);
      }
    } else if (b.header === '[vars]') {
      const urls: Record<string, string> = { APP_URL: o.url, SITE_URL: o.url, MCP_URL: `${o.url}/mcp` };
      // WORKERS_DEV_SUBDOMAIN names our account: kept, it would let our web app make credentialed
      // calls to a self-hosted instance. Without it CORS allows only SITE_URL and APP_URL.
      lines = b.lines.flatMap((line) => {
        const key = line.split('=')[0]!.trim();
        if (key === 'WORKERS_DEV_SUBDOMAIN') return [];
        return [key in urls ? `${key} = ${JSON.stringify(urls[key])}` : line];
      });
      lines.push('SELF_HOSTED = "true"');
    } else if (b.header === '[[kv_namespaces]]') {
      const id = o.kvIds[value(b, 'binding') ?? ''];
      if (!id) throw new Error(`No namespace id for KV binding ${value(b, 'binding')}`);
      lines = set(b, 'id', id);
    } else if (b.header === '[[r2_buckets]]') {
      lines = set(b, 'bucket_name', resourceName(o.name, value(b, 'binding')!));
    } else if (b.header === '[[vectorize]]') {
      lines = set(b, 'index_name', resourceName(o.name, value(b, 'binding')!));
    } else if (b.header === '[[services]]') {
      // Only SELF survives, renamed to this worker: any other service is a production worker.
      if (value(b, 'binding') !== 'SELF' || !o.selfBinding) continue;
      lines = set(b, 'service', o.name);
    } else if (DROP.has(b.header)) {
      continue;
    } else if (KEEP.has(b.header)) {
      lines = b.lines;
    } else {
      throw new Error(`selfhost.ts does not know section ${b.header}; decide whether a self-hosted deploy keeps it`);
    }
    if (b.header) out.push('', b.header);
    out.push(...lines);
  }
  return `${out.join('\n')}\n`;
}

export function bindings(prod: string, header: string): string[] {
  return blocks(prod).filter((b) => b.header === header).map((b) => value(b, 'binding')!);
}

// A worker that already exists must be one this script deployed. Every version it serves
// must carry SELF_HOSTED="true", which only the self-host template sets; production never does.
// Returns whether the worker exists.
export function ownWorker(name: string, wrangler: (argv: string[]) => string): boolean {
  let status: { versions?: Array<{ version_id: string }> };
  try {
    status = JSON.parse(wrangler(['deployments', 'status', '--name', name, '--json']));
  } catch (err) {
    if (/does not exist|\[code: 10007\]/.test(err instanceof Error ? err.message : String(err))) return false;
    throw err;
  }
  const versions = status.versions ?? [];
  const selfHostedVersion = (id: string) => {
    const view = JSON.parse(wrangler(['versions', 'view', id, '--name', name, '--json'])) as {
      resources?: { bindings?: Array<{ type: string; name: string; text?: string }> };
    };
    return view.resources?.bindings?.some((b) => b.type === 'plain_text' && b.name === 'SELF_HOSTED' && b.text === 'true') ?? false;
  };
  if (!versions.length || !versions.every((v) => selfHostedVersion(v.version_id))) {
    throw new Error(`A worker named "${name}" already exists on this account and was not deployed by pnpm selfhost. Pick another --name.`);
  }
  return true;
}

const randomHex = () => Array.from(crypto.getRandomValues(new Uint8Array(32)), (b) => b.toString(16).padStart(2, '0')).join('');

// The backup is on disk before any secret is set, so a failure partway never leaves a
// set secret whose value is lost.
export async function setMissingSecrets(
  existing: string[],
  put: (name: string, value: string) => void,
  backup?: (values: Record<string, string>) => Promise<void>,
): Promise<Record<string, string>> {
  const generated = Object.fromEntries(
    SECRETS.filter((s) => !existing.includes(s)).map((s) => [s, s === 'BUCKET_KEK_VERSION' ? '1' : randomHex()]),
  );
  if (backup && Object.keys(generated).length) await backup(generated);
  for (const [name, value] of Object.entries(generated)) put(name, value);
  return generated;
}

export const BOOTSTRAP_SECRET = 'SELF_HOSTED_BOOTSTRAP_TOKEN';

export interface Registration {
  api_key: string;
  org_id: string;
}

export interface ProvisionOptions {
  // Runs cleanup on Ctrl-C or SIGTERM while the bootstrap token is set; returns the unhook.
  onInterrupt: (cleanup: () => void) => () => void;
  deploy: () => void;
  wrangler: (argv: string[], input?: string) => string;
  configPath: string;
  kvId: string;
  forceRegister: boolean;
  backup?: (values: Record<string, string>) => Promise<void>;
  register: (token: string) => Promise<Registration>;
}

// The worker goes live with registration closed (no bootstrap secret), then the secrets
// land, then a one-time token opens /v1/register for the operator's own request and is
// deleted straight after. The token only ever travels over stdin and in a request header.
export async function provision(o: ProvisionOptions): Promise<{ generated: Record<string, string>; registered: Registration | null }> {
  o.deploy();
  const secret = (verb: 'put' | 'delete', name: string, input?: string) => o.wrangler(['secret', verb, name, '-c', o.configPath], input);
  const existing = (JSON.parse(o.wrangler(['secret', 'list', '-c', o.configPath, '--format', 'json'])) as Array<{ name: string }>).map((s) => s.name);
  const generated = await setMissingSecrets(existing.filter((s) => s !== BOOTSTRAP_SECRET), (name, v) => { secret('put', name, v); }, o.backup);
  const orgs = JSON.parse(o.wrangler(['kv', 'key', 'list', '--namespace-id', o.kvId, '--prefix', 'org:', '--remote'])) as unknown[];
  if (orgs.length && !o.forceRegister) {
    // Left behind by a run that died before deleting it.
    if (existing.includes(BOOTSTRAP_SECRET)) secret('delete', BOOTSTRAP_SECRET);
    return { generated, registered: null };
  }
  let closed = false;
  const close = () => {
    if (closed) return;
    closed = true;
    try {
      secret('delete', BOOTSTRAP_SECRET);
    } catch {
      // Never let this hide a key that was just issued; the random token stays unguessable meanwhile.
      console.error(`\nCould not delete ${BOOTSTRAP_SECRET}. Close registration with: wrangler secret delete ${BOOTSTRAP_SECRET} -c ${o.configPath}`);
    }
  };
  const token = randomHex();
  const unhook = o.onInterrupt(close);
  try {
    secret('put', BOOTSTRAP_SECRET, token);
    return { generated, registered: await o.register(token) };
  } finally {
    close();
    unhook();
  }
}

export interface RegisterOptions {
  fetchImpl?: typeof fetch;
  sleep?: (ms: number) => Promise<void>;
  attempts?: number;
  timeoutMs?: number;
}

// Retries only what can clear up: a network error or timeout, and 403 registration_closed,
// which means the bootstrap secret hasn't reached this location yet. Anything else is final.
export async function registerWithToken(url: string, token: string, o: RegisterOptions = {}): Promise<Registration> {
  const doFetch = o.fetchImpl ?? fetch;
  const sleep = o.sleep ?? ((ms: number) => new Promise<void>((r) => setTimeout(r, ms)));
  const attempts = o.attempts ?? 10;
  let last = 'no response';
  for (let attempt = 0; attempt < attempts; attempt++) {
    if (attempt) await sleep(3000);
    let res: Response;
    try {
      res = await doFetch(`${url}/v1/register`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'X-Bootstrap-Token': token },
        body: JSON.stringify({ agent_name: 'admin', org_name: 'Self-hosted' }),
        signal: AbortSignal.timeout(o.timeoutMs ?? 15_000),
      });
    } catch (err) {
      last = err instanceof Error ? err.message : String(err);
      continue;
    }
    const body = (await res.json().catch(() => null)) as { data?: Registration; code?: string; error?: string } | null;
    if (res.ok && body?.data) return body.data;
    last = `${res.status} ${body?.error ?? ''}`.trim();
    if (!(res.status === 403 && body?.code === 'registration_closed')) break;
  }
  throw new Error(`POST ${url}/v1/register failed (${last}); check ${url}/v1/health, then re-run with --register`);
}

export function workersDevUrl(output: string): string | undefined {
  return /https:\/\/[a-z0-9-]+\.[a-z0-9-]+\.workers\.dev/.exec(output)?.[0];
}

async function main(): Promise<void> {
  const { parseArgs } = await import('node:util');
  const { execFileSync, spawnSync } = await import('node:child_process');
  const fs = await import('node:fs/promises');
  const { existsSync, writeFileSync } = await import('node:fs');
  const path = await import('node:path');
  const { fileURLToPath } = await import('node:url');

  const { values: args } = parseArgs({
    options: {
      name: { type: 'string', default: 'agentdrive' },
      'backup-secrets': { type: 'string' },
      register: { type: 'boolean', default: false },
      'dry-run': { type: 'boolean', default: false },
    },
  });
  const name = args.name!;
  if (!/^[a-z0-9][a-z0-9-]{1,40}[a-z0-9]$/.test(name)) throw new Error('--name must be 3-42 lowercase letters, digits or hyphens');
  const dryRun = args['dry-run']!;
  const backupFile = args['backup-secrets'] && path.resolve(args['backup-secrets']);

  const workerDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const repoRoot = path.resolve(workerDir, '../..');
  const configPath = path.join(workerDir, 'wrangler.selfhost.toml');
  const prod = await fs.readFile(path.join(workerDir, 'wrangler.toml'), 'utf8');

  const appsDir = path.join(repoRoot, 'apps');
  const production = [];
  for (const app of await fs.readdir(appsDir)) {
    const toml = path.join(appsDir, app, 'wrangler.toml');
    if (existsSync(toml)) production.push(value(blocks(await fs.readFile(toml, 'utf8'))[0]!, 'name'));
  }
  if (production.includes(name)) throw new Error(`--name ${name} is a production AgentDrive worker; pick another name`);
  if (backupFile) {
    if (existsSync(backupFile)) throw new Error(`--backup-secrets ${backupFile} already exists; pass a new file`);
    await fs.access(path.dirname(backupFile), (await import('node:fs')).constants.W_OK);
  }

  const run = (cmd: string, argv: string[], opts: { cwd?: string; input?: string } = {}): string => {
    const res = spawnSync(cmd, argv, { cwd: opts.cwd ?? workerDir, input: opts.input, encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] });
    if (res.status !== 0) {
      const err = new Error(`${cmd} ${argv.slice(0, 4).join(' ')} failed:\n${res.stderr || res.stdout}`);
      Object.assign(err, { stdout: res.stdout, stderr: res.stderr });
      throw err;
    }
    return res.stdout;
  };
  const wrangler = (argv: string[], input?: string) => run('pnpm', ['exec', 'wrangler', ...argv], { input });
  const succeeds = (argv: string[]) => {
    try { wrangler(argv); return true; } catch { return false; }
  };
  const step = (msg: string) => console.log(`\n== ${msg}`);

  console.log('AgentDrive self-host (community-supported; the hosted service at agentdrive.sh is the supported product).\n');
  console.log(PLAN_NOTE);

  const build = () => {
    step('Building the worker and its workspace packages');
    execFileSync('pnpm', ['turbo', 'run', 'build', '--filter=@agentdrive/worker^...'], { cwd: repoRoot, stdio: 'inherit' });
    execFileSync('pnpm', ['run', 'generate'], { cwd: workerDir, stdio: 'inherit' });
  };

  const kvBindings = bindings(prod, '[[kv_namespaces]]');

  if (dryRun) {
    const kvIds = Object.fromEntries(kvBindings.map((b, i) => [b, String(i + 1).repeat(32)]));
    await fs.writeFile(configPath, selfhostConfig(prod, { name, url: PLACEHOLDER_URL, kvIds, selfBinding: true }));
    console.log(`\nWrote ${path.relative(repoRoot, configPath)} with placeholder IDs.`);
    build();
    step('wrangler deploy --dry-run');
    const outdir = await fs.mkdtemp(path.join((await import('node:os')).tmpdir(), 'agentdrive-selfhost-'));
    execFileSync('pnpm', ['exec', 'wrangler', 'deploy', '--dry-run', '--outdir', outdir, '-c', configPath], { cwd: workerDir, stdio: 'inherit' });
    console.log('\nDry run passed. Nothing was created or deployed.');
    return;
  }

  step('Checking your wrangler login');
  try {
    const who = wrangler(['whoami']);
    if (/not authenticated/i.test(who)) throw new Error('not authenticated');
  } catch {
    throw new Error('wrangler is not logged in. Run `pnpm --filter @agentdrive/worker exec wrangler login` and re-run.');
  }
  const exists = ownWorker(name, wrangler);
  console.log(exists ? `Worker ${name} was deployed by pnpm selfhost; redeploying it.` : `Worker ${name} is new.`);

  step('KV namespaces');
  const listKv = () => JSON.parse(wrangler(['kv', 'namespace', 'list'])) as Array<{ id: string; title: string }>;
  let namespaces = listKv();
  const kvIds: Record<string, string> = {};
  for (const binding of kvBindings) {
    const title = resourceName(name, binding);
    if (!namespaces.some((n) => n.title === title)) {
      wrangler(['kv', 'namespace', 'create', title]);
      namespaces = listKv();
    }
    const id = namespaces.find((n) => n.title === title)?.id;
    if (!id) throw new Error(`KV namespace ${title} was not found after creating it`);
    kvIds[binding] = id;
    console.log(`${binding}: ${title} (${id})`);
  }

  step('R2 bucket');
  for (const binding of bindings(prod, '[[r2_buckets]]')) {
    const bucket = resourceName(name, binding);
    if (!succeeds(['r2', 'bucket', 'info', bucket])) wrangler(['r2', 'bucket', 'create', bucket]);
    console.log(`${binding}: ${bucket}`);
  }

  step('Vectorize index');
  for (const binding of bindings(prod, '[[vectorize]]')) {
    const index = resourceName(name, binding);
    let existing: { config?: { dimensions?: number; metric?: string } } | null = null;
    try { existing = JSON.parse(wrangler(['vectorize', 'get', index, '--json'])); } catch { existing = null; }
    if (!existing) {
      wrangler(['vectorize', 'create', index, `--dimensions=${VECTORIZE.dimensions}`, `--metric=${VECTORIZE.metric}`]);
    } else if (existing.config?.dimensions !== VECTORIZE.dimensions || existing.config?.metric !== VECTORIZE.metric) {
      throw new Error(`Vectorize index ${index} exists with ${JSON.stringify(existing.config)}; it needs ${VECTORIZE.dimensions} dimensions and ${VECTORIZE.metric}`);
    }
    const indexed = (JSON.parse(wrangler(['vectorize', 'list-metadata-index', index, '--json']) || '[]') as Array<{ propertyName: string }>)
      .map((m) => m.propertyName);
    for (const property of VECTORIZE.metadata.filter((p) => !indexed.includes(p))) {
      wrangler(['vectorize', 'create-metadata-index', index, '--propertyName', property, '--type', 'string']);
    }
    console.log(`${binding}: ${index} (${VECTORIZE.dimensions} dimensions, ${VECTORIZE.metric})`);
  }

  // The workers.dev URL is only known after the first deploy, and APP_URL/SITE_URL/MCP_URL
  // must name it, so a first run deploys twice.
  const previous = existsSync(configPath) ? value(blocks(await fs.readFile(configPath, 'utf8')).find((b) => b.header === '[vars]')!, 'APP_URL') : undefined;
  let url = previous ?? PLACEHOLDER_URL;
  const deploy = () => {
    step('Deploying');
    const out = wrangler(['deploy', '-c', configPath]);
    console.log(out.trim());
    const deployed = workersDevUrl(out);
    if (!deployed) throw new Error('Deployed, but no workers.dev URL was printed. Enable the workers.dev subdomain for your account and re-run.');
    return deployed;
  };
  let selfBinding = exists;
  const writeBackup = async (values: Record<string, string>) => {
    const file = await fs.open(backupFile!, 'wx', 0o600);
    try {
      await file.writeFile(`${JSON.stringify(values, null, 2)}\n`);
      await file.sync();
    } finally {
      await file.close();
    }
    console.log(`Backed up the generated secrets to ${backupFile} (mode 0600) before setting them. Keep it out of git.`);
  };
  const register = (token: string): Promise<Registration> => {
    step('Registering an owner key');
    return registerWithToken(url, token);
  };
  const onInterrupt = (cleanup: () => void) => {
    const stop = (signal: NodeJS.Signals) => {
      cleanup();
      process.exit(signal === 'SIGINT' ? 130 : 143);
    };
    process.once('SIGINT', stop);
    process.once('SIGTERM', stop);
    return () => { process.off('SIGINT', stop); process.off('SIGTERM', stop); };
  };

  await fs.writeFile(configPath, selfhostConfig(prod, { name, url, kvIds, selfBinding }));
  build();
  const { generated, registered } = await provision({
    deploy: () => {
      const deployed = deploy();
      if (deployed !== url || !selfBinding) {
        url = deployed;
        selfBinding = true;
        writeFileSync(configPath, selfhostConfig(prod, { name, url, kvIds, selfBinding }));
        deploy();
      }
      step('Secrets');
    },
    onInterrupt,
    wrangler,
    configPath,
    kvId: kvIds.KV!,
    forceRegister: args.register!,
    backup: backupFile ? writeBackup : undefined,
    register,
  });
  for (const secret of SECRETS) console.log(`${secret}: ${secret in generated ? 'generated and set' : 'already set, kept'}`);
  if (backupFile && !Object.keys(generated).length) {
    console.log('No secrets were generated this run, so there is nothing to back up; Cloudflare never returns secret values.');
  }

  if (registered) {
    console.log(`\nIssued an owner key for org ${registered.org_id}. It is shown once; store it now.\n`);
    console.log('Connect the CLI (reads the key from stdin; needs @adrive/cli with `auth login --with-key`):\n');
    console.log(`  printf '%s' '${registered.api_key}' | npx @adrive/cli auth login --api-url ${url} --with-key\n`);
  } else {
    console.log('\nThis instance already has an organization. Keep using its key, or re-run with --register to issue a new one.');
  }
  console.log('Give each teammate their own key, minted with yours:\n');
  console.log(`  curl -X POST ${url}/v1/keys -H "Authorization: Bearer $AGENTDRIVE_KEY" -H 'Content-Type: application/json' -d '{"name":"teammate"}'\n`);
  console.log(`AgentDrive API: ${url}  (health: ${url}/v1/health)`);
}

if (typeof process !== 'undefined' && process.argv?.[1]?.endsWith('selfhost.ts')) {
  main().catch((error) => { console.error(`\n${error instanceof Error ? error.message : String(error)}`); process.exitCode = 1; });
}
