#!/usr/bin/env node
// Reads apps/installer/install.sh and writes apps/worker/src/generated/install-script.ts
// exporting the script as a string constant. Run via:
//   node apps/installer/build.mjs
// Wired into the worker via the "prebuild" script in apps/worker/package.json.

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..', '..');
const srcPath = join(here, 'install.sh');
const outDir = join(repoRoot, 'apps', 'worker', 'src', 'generated');
const outPath = join(outDir, 'install-script.ts');

const sh = await readFile(srcPath, 'utf8');
if (!sh.startsWith('#!/bin/sh')) {
  console.error(`install.sh must start with "#!/bin/sh" shebang`);
  process.exit(1);
}

const sha256 = createHash('sha256').update(sh).digest('hex');

const literal = JSON.stringify(sh);

const body = `// Generated by apps/installer/build.mjs from apps/installer/install.sh
// DO NOT EDIT BY HAND. Re-run \`node apps/installer/build.mjs\` to regenerate.
// source-sha256: ${sha256}

export const INSTALL_SCRIPT: string = ${literal};

export const INSTALL_SCRIPT_SHA256 = ${JSON.stringify(sha256)};
`;

await mkdir(outDir, { recursive: true });
await writeFile(outPath, body, 'utf8');

console.log(`wrote ${outPath} (${sh.length} bytes, sha256 ${sha256.slice(0, 12)}...)`);
