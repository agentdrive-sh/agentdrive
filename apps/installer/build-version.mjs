#!/usr/bin/env node
// Reads packages/mcp-server/package.json + packages/sdk-ts/package.json +
// packages/cli/package.json and writes apps/worker/src/generated/version.ts
// exporting the resolved versions. Run via:
//   node apps/installer/build-version.mjs
// Wired into the worker via "prebuild" / "pretypecheck" / "pretest" alongside
// the install-script generator.
//
// Phase 0 deliverable #1: kill the hardcoded /v1/health "0.3.0" string drift.

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..', '..');

async function readVersion(pkgRelPath) {
  const full = join(repoRoot, pkgRelPath);
  const raw = await readFile(full, 'utf8');
  const pkg = JSON.parse(raw);
  if (typeof pkg.version !== 'string' || pkg.version.length === 0) {
    throw new Error(`${pkgRelPath} has no version field`);
  }
  return pkg.version;
}

const mcpVersion = await readVersion('packages/mcp-server/package.json');
const sdkVersion = await readVersion('packages/sdk-ts/package.json').catch(() => null);
const cliVersion = await readVersion('packages/cli/package.json');

const outDir = join(repoRoot, 'apps', 'worker', 'src', 'generated');
const outPath = join(outDir, 'version.ts');

const body = `// Generated by apps/installer/build-version.mjs from package versions.
// DO NOT EDIT BY HAND. Re-run \`node apps/installer/build-version.mjs\` (or any
// worker build/test/typecheck script) to regenerate.

export const MCP_SERVER_VERSION = ${JSON.stringify(mcpVersion)};
export const SDK_VERSION: string | null = ${JSON.stringify(sdkVersion)};
export const CLI_VERSION = ${JSON.stringify(cliVersion)};

// The /v1/health version reports the MCP server version because that's the
// surface external readers most often pin against.
export const WORKER_HEALTH_VERSION = MCP_SERVER_VERSION;
`;

await mkdir(outDir, { recursive: true });
await writeFile(outPath, body, 'utf8');

console.log(
  `wrote ${outPath} (mcp=${mcpVersion}, sdk=${sdkVersion ?? '<absent>'}, cli=${cliVersion})`,
);
