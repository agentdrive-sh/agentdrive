// Same form as plugins/agentdrive/hooks/hooks.json, which also pins the version for the plugin directory. GUI-launched harnesses can
// miss the global npm bin on PATH, so fall back to npx rather than fail.
export function hookCommand(harness: string, event?: string): string {
  const args = event ? `${harness} --event ${event}` : harness;
  return `command -v adrive >/dev/null 2>&1 && adrive hook ${args} || npx -y @adrive/cli hook ${args}`;
}

type Json = Record<string, unknown>;

function asObject(v: unknown): Json {
  return v && typeof v === 'object' && !Array.isArray(v) ? { ...(v as Json) } : {};
}

function isOurCommand(command: unknown): boolean {
  return typeof command === 'string' && command.includes('adrive hook');
}

// Replaces our entry where it already sits (dropping duplicates) or appends
// it, so foreign hooks keep their order and a re-run is byte-identical.
function upsert(list: unknown, desired: Json, isOurs: (entry: Json) => boolean): unknown[] {
  const entries = Array.isArray(list) ? list : [];
  const first = entries.findIndex((e) => isOurs(asObject(e)));
  if (first === -1) return [...entries, desired];
  return entries.flatMap((e, i) => (i === first ? [desired] : isOurs(asObject(e)) ? [] : [e]));
}

function groupIsOurs(group: Json): boolean {
  return Array.isArray(group.hooks) && group.hooks.some((h) => isOurCommand(asObject(h).command));
}

// Codex and Gemini CLI use Claude Code's {event: [{matcher?, hooks: [handler]}]} shape.
export function mergeGroupedHooks(existing: Json, groups: Record<string, Json>): Json {
  const hooks = asObject(existing.hooks);
  for (const [event, group] of Object.entries(groups)) {
    hooks[event] = upsert(hooks[event], group, groupIsOurs);
  }
  return { ...existing, hooks };
}

export function codexHookGroups(): Record<string, Json> {
  // Codex clamps hook timeouts above 3s and reports it as an error item on every run.
  const group = { hooks: [{ type: 'command', command: hookCommand('codex'), timeout: 3 }] };
  return { SessionStart: group, Stop: group, SessionEnd: group, PreCompact: group };
}

export function geminiHookGroups(): Record<string, Json> {
  // Gemini CLI timeouts are milliseconds.
  const group = {
    matcher: '*',
    hooks: [{ type: 'command', command: hookCommand('gemini-cli'), timeout: 10000, name: 'agentdrive' }],
  };
  return { SessionStart: group, AfterAgent: group, SessionEnd: group, PreCompress: group };
}

export function mergeCursorHooks(existing: Json): Json {
  const hooks = asObject(existing.hooks);
  const entry = { command: hookCommand('cursor'), timeout: 10 };
  for (const event of ['sessionStart', 'stop', 'sessionEnd', 'preCompact']) {
    hooks[event] = upsert(hooks[event], entry, (e) => isOurCommand(e.command));
  }
  return { version: 1, ...existing, hooks };
}

// Antigravity's hooks.json is keyed by hook name. Its payloads carry no event
// name, so each event gets its own command. A user's `enabled: false` survives re-wiring.
export function mergeAntigravityHooks(existing: Json): Json {
  const handler = (event: string) => [{ type: 'command', command: hookCommand('antigravity', event), timeout: 10 }];
  const enabled = asObject(existing.agentdrive).enabled === false ? { enabled: false } : {};
  return { ...existing, agentdrive: { ...enabled, SessionStart: handler('SessionStart'), Stop: handler('Stop') } };
}

// Loaded by OpenCode's Bun runtime from ~/.config/opencode/plugins/. It hands
// the session to `adrive hook opencode` (npx when `init` ran without a global
// install) and never waits on it or surfaces errors, so a missing or slow adrive
// cannot stall OpenCode.
export const OPENCODE_PLUGIN = `// Generated by \`adrive init\`. Re-run init to update; edits are overwritten.
import { spawn } from 'node:child_process';

function send(payload: Record<string, unknown>): void {
  try {
    const child = spawn(${JSON.stringify(hookCommand('opencode'))}, { shell: true, stdio: ['pipe', 'ignore', 'ignore'], detached: true });
    child.on('error', () => {});
    child.stdin?.on('error', () => {});
    child.stdin?.end(JSON.stringify(payload));
    child.unref();
  } catch {}
}

interface OpencodeEvent {
  type: string;
  properties?: { info?: { id?: string; parentID?: string; directory?: string }; sessionID?: string };
}

export const AgentDrive = async ({ directory }: { directory: string }) => ({
  event: async ({ event }: { event: OpencodeEvent }) => {
    if (event.type === 'session.created') {
      const info = event.properties?.info;
      if (!info?.id || info.parentID) return;
      send({ hook_event_name: 'session.created', session_id: info.id, cwd: info.directory ?? directory });
    } else if (event.type === 'session.idle' && event.properties?.sessionID) {
      send({ hook_event_name: 'session.idle', session_id: event.properties.sessionID, cwd: directory });
    }
  },
});

export default { id: 'agentdrive', server: AgentDrive };
`;

export function harnessRoot(harness: HookHarness, home: string, env: NodeJS.ProcessEnv = process.env): string {
  switch (harness) {
    case 'codex':
      return codexHome(env, home);
    case 'opencode':
      return opencodeConfigDir(env, home);
    case 'gemini-cli':
      return join(home, '.gemini');
    case 'cursor':
      return join(home, '.cursor');
    case 'antigravity':
      return join(home, '.gemini', 'config');
  }
}

// Codex dropped custom prompts in rust-v0.118.0; its skill covers resume and sessions.
const COMMAND_DIRS: Partial<Record<HookHarness, string>> = {
  opencode: 'commands',
  'gemini-cli': join('commands', 'agentdrive'),
  cursor: 'commands',
  antigravity: 'skills',
};

export async function harnessInstalled(harness: HookHarness, home: string, env: NodeJS.ProcessEnv = process.env): Promise<boolean> {
  try {
    return (await fs.stat(harnessRoot(harness, home, env))).isDirectory();
  } catch {
    return false;
  }
}

export interface HarnessWiring {
  changed: string[];
  warnings: string[];
}

export async function wireHarness(harness: HookHarness, home: string, env: NodeJS.ProcessEnv = process.env): Promise<HarnessWiring> {
  const root = harnessRoot(harness, home, env);
  const result: HarnessWiring = { changed: [], warnings: [] };
  const track = async (path: string, write: Promise<WriteAction>) => {
    if ((await write) !== 'unchanged') result.changed.push(path);
  };
  const mergeJson = async (path: string, merge: (existing: Json) => Json) =>
    track(path, writeJsonIfChanged(path, merge((await readJsonObject(path)) ?? {})));

  switch (harness) {
    case 'codex': {
      await mergeJson(join(root, 'hooks.json'), (e) => mergeGroupedHooks(e, codexHookGroups()));
      const toml = join(root, 'config.toml');
      await track(toml, writeFileIfChanged(toml, mergeCodexToml((await readTextIfExists(toml)) ?? ''), { backup: true }));
      break;
    }
    case 'opencode': {
      const json = join(root, 'opencode.json');
      const jsonc = join(root, 'opencode.jsonc');
      if ((await readTextIfExists(json)) === null && (await readTextIfExists(jsonc)) !== null) {
        // A fresh OpenCode writes plain JSON into opencode.jsonc; only real JSONC would lose comments on a merge.
        if (await readJsonObject(jsonc).then(() => true, () => false)) await mergeJson(jsonc, mergeOpencodeJson);
        else result.warnings.push('opencode.jsonc has comments; add the agentdrive MCP entry to it by hand (they would be lost if merged)');
      } else {
        await mergeJson(json, mergeOpencodeJson);
      }
      const plugin = join(root, 'plugins', 'agentdrive.ts');
      await track(plugin, writeFileIfChanged(plugin, OPENCODE_PLUGIN));
      break;
    }
    case 'gemini-cli':
      await mergeJson(join(root, 'settings.json'), (e) => mergeGroupedHooks(mergeMcpJson(e, 'gemini-cli'), geminiHookGroups()));
      break;
    case 'cursor':
      await mergeJson(join(root, 'hooks.json'), mergeCursorHooks);
      await mergeJson(join(root, 'mcp.json'), (e) => mergeMcpJson(e, 'cursor'));
      break;
    case 'antigravity':
      await mergeJson(join(root, 'hooks.json'), mergeAntigravityHooks);
      await mergeJson(join(root, 'mcp_config.json'), (e) => mergeMcpJson(e, 'antigravity'));
      break;
  }

  const commandDir = COMMAND_DIRS[harness];
  for (const name of commandDir ? HARNESS_COMMANDS : []) {
    const path = join(root, commandDir!, commandFileName(harness, name));
    await track(path, writeFileIfChanged(path, renderCommand(harness, name)));
  }
  if (harness !== 'gemini-cli') {
    const skill = join(root, 'skills', 'agentdrive', 'SKILL.md');
    await track(skill, writeFileIfChanged(skill, SKILL_MARKDOWN));
  }
  return result;
}

// CLI 1.0.0 wrote this skill; the Claude Code plugin now ships it, and OpenCode
// also loads ~/.claude/skills, so the copy shows up as a duplicate skill there.
export async function removeLegacyClaudeSkill(home: string): Promise<string | null> {
  const dir = join(home, '.claude', 'skills', 'agentdrive');
  const skill = join(dir, 'SKILL.md');
  // A linked folder is shared with other agents or a dev checkout; deleting through it would reach outside ~/.claude.
  if (!(await fs.lstat(dir).then((st) => st.isDirectory(), () => false))) return null;
  const text = await readTextIfExists(skill);
  const frontmatter = text && /^---\r?\n([\s\S]*?)\r?\n---/.exec(text)?.[1];
  if (!frontmatter || !/^name:[ \t]*agentdrive[ \t]*\r?$/m.test(frontmatter)) return null;
  await fs.rm(skill);
  // Anything else the user put there stays.
  await fs.rmdir(dir).catch(() => undefined);
  return skill;
}

// This repo is private; agentdrive-mcp carries a public copy of .claude-plugin/ and plugins/.
export const CLAUDE_MARKETPLACE = 'agentdrive-sh/agentdrive-mcp';
export const CLAUDE_MANUAL_STEPS = [
  `/plugin marketplace add ${CLAUDE_MARKETPLACE}`,
  '/plugin install agentdrive@agentdrive',
];

export type ClaudePluginResult = { status: 'installed' } | { status: 'no-claude' } | { status: 'failed'; detail: string };

// User settings pin a marketplace's source (installs before CLI 1.3.1 pinned Rakesh1002/agentdrive-mcp,
// which GitHub redirects), and Claude Code refuses to re-add it from any other source.
function claudeMarketplaceConfigured(): boolean {
  const run = spawnSync('claude', ['plugin', 'marketplace', 'list', '--json'], { encoding: 'utf8', timeout: 120_000 });
  try {
    return (JSON.parse(run.stdout) as { name?: unknown }[]).some((m) => m.name === 'agentdrive');
  } catch {
    return false;
  }
}

export function installClaudePlugin(stdio: 'inherit' | 'ignore' = 'inherit'): ClaudePluginResult {
  const steps = [
    ...(claudeMarketplaceConfigured() ? [] : [['plugin', 'marketplace', 'add', CLAUDE_MARKETPLACE, '--scope', 'user']]),
    ['plugin', 'install', 'agentdrive@agentdrive', '-s', 'user', '-y'],
  ];
  for (const args of steps) {
    // A hung `claude` would otherwise hold the sync lock when this runs from a session-start hook.
    const run = spawnSync('claude', args, { stdio, timeout: 120_000 });
    if ((run.error as NodeJS.ErrnoException | undefined)?.code === 'ENOENT') return { status: 'no-claude' };
    if (run.error) return { status: 'failed', detail: run.error.message };
    if (run.status !== 0) return { status: 'failed', detail: `\`claude ${args.join(' ')}\` exited ${run.status}` };
  }
  return { status: 'installed' };
}
